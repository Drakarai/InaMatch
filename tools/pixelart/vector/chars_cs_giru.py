def fringe(pts, c='mid'):
    """Flequillo por delante de la cara (las puntas, con un tercer valor, afiladas)."""
    return L(outline(pts), c, 'f')


def ring(cx, cy, r, c=OUTC, w=1.6):
    e = ell(cx, cy, r, r)
    return L(e + [e[0]], c, 'f', False, False, w)


