"""Los Fertilia (Ratoniik Eleven, gx-ratoniik-eleven): alienígenas insecto del planeta Ratoniik, con sus modelos 3D de
Inazuma Eleven GO Galaxy como referencia (busto de frente, perfil y espalda).

Los contornos están calcados en píxeles de cada referencia (b0 de frente, b6 de perfil, b4 de espalda) y se pasan a unidades
de cabeza con T(): el punto entre los ojos va a (50, 75) de frente, el ojo a (80, 75) de perfil, y el centro de la cabeza a
x = 50 de espaldas. ANCH guarda esas anclas por jugador (las usa la hoja de repaso con el dibujo encima de la referencia).
"""
from chars import CHARS, L, OUTC, ell, outline, pal, strand
from heads import quad  # noqa: F401

WHITE = (248, 248, 248, 255)
ANCH = {}


def T(cx, ey, s, ex=50, k=1.0, vy=None, ev=75):
    """Píxeles de la referencia -> unidades de cabeza (s: px por unidad en horizontal; vy: en vertical)."""
    vy = vy or 0.776 * s

    def f(pts):
        return [(round(ex + (p[0] - cx) / (s * k), 1), round(ev + (p[1] - ey) / vy, 1)) + tuple(p[2:]) for p in pts]
    f.a = (cx, ey, s, ex, k, vy, ev)
    return f


def views(pid, front, side, back):
    ANCH[pid] = {'front': front.a, 'side': side.a, 'back': back.a}


def O(tf, pts, c='mid', z='b', sil=True, ln=False):
    return L(outline(tf(pts)), c, z, sil, ln)


def E(tf, x, y, rx, ry, c, z='f', ln=True, sil=False):
    a = tf([(x - rx, y - ry), (x + rx, y + ry)])
    (u0, v0), (u1, v1) = a[0][:2], a[1][:2]
    return L(ell((u0 + u1) / 2, (v0 + v1) / 2, abs(u1 - u0) / 2, abs(v1 - v0) / 2), c, z, sil, ln)


def S(tf, pts, c='deep', z='b', w=1.0):
    return strand(tf(pts), c, z, w)


def mirror(pts, cx):
    return [(2 * cx - p[0], p[1]) + tuple(p[2:]) for p in reversed(pts)]


